def facts():
    out = []
    for line in CURATED.splitlines():
        category, q1, q2, a = line.split('|')
        out.append(dict(category=category, questions=[q1, q2], answers=[a, a + '.'], verification='editorial-stable-knowledge'))
    # Unique integer equations: commutative pairs are stored only once.
    for op in ['+', '-', '*']:
        for x in range(26):
            for y in range(26):
                if op == '-' and y > x:
                    continue
                if op in ('+','*') and y < x:
                    continue
                a = x+y if op == '+' else x-y if op == '-' else x*y
                out.append(dict(category='арифметика', questions=['сколько будет %d%s%d?' % (x,op,y), 'вычисли %d%s%d.' % (x,op,y)], answers=[str(a), str(a)+'.'], verification='integer-oracle', expression=[x,op,y]))
    for q,thing in [('какой у меня пароль?','мой пароль'),('как меня зовут?','моё имя'),('какой у меня адрес?','мой адрес'),('какой у меня номер телефона?','номер моего телефона'),('какой у меня рост?','мой рост'),('сколько я вешу?','мой вес'),('какой мой любимый цвет?','мой любимый цвет'),('сколько мне лет?','мой возраст'),('в каком городе я живу?','мой город'),('когда у меня день рождения?','мой день рождения')]:
        out.append(dict(category='неизвестное', questions=[q, 'назови %s.' % thing], answers=['не знаю', 'не знаю.'], verification='unavailable-personal-information'))
    for q in ['сколько будет 1/0?', 'какая столица у солнца?', 'какого цвета число семь?', 'какая столица у числа семь?', 'где живёт квадратный круг?']:
        out.append(dict(category='неизвестное', questions=[q, 'подскажи: '+q], answers=['некорректный вопрос', 'некорректный вопрос.'], verification='invalid-premise'))
    for i, f in enumerate(out):
        f['id'] = 'ru-%04d' % i
        a=f['answers'][0]
        if f['category']=='география' and f['questions'][0].startswith('как называется столица '):
            country=f['questions'][0][len('как называется столица '):].rstrip('?')
            alternate='столица '+country+' - '+a
        elif a=='не знаю':alternate='я не знаю'
        elif a=='некорректный вопрос':alternate='вопрос некорректен'
        else:alternate='ответ: '+a
        f['answers'].append(alternate+'.')
    return out


def build(destination=ROOT/'data', seed=42):
    destination = Path(destination)
    destination.mkdir(parents=True, exist_ok=True)
    fs = facts()
    form_rng=random.Random(seed)
    train, test = [], []
    for f in fs:
        # Rotate the trained form across facts; reserve the other true paraphrase.
        # The prefix supplies a second training form without leaking the held-out one.
        f['train_form']=form_rng.randrange(2)
        trained_q=f['questions'][f['train_form']]
        held_q=f['questions'][1-f['train_form']]
        for q in [trained_q, 'скажи: '+trained_q]:
            for a in f['answers']:
                train.append(dict(fact_id=f['id'], category=f['category'], question=q, answer=a))
        # A whole question form is held out, answers/facts remain known.
        test.append(dict(fact_id=f['id'], category=f['category'], question=held_q, answers=f['answers'], split='paraphrase'))
    seen = set()
    for e in train + test:
        q = normalize(e['question'])
        answers = [e['answer']] if 'answer' in e else e['answers']
        for a in answers:
            if any(c in q+a for c in '\r\n'):raise ValueError('Embedded line break in QA')
            seq = encode(q+'\n'+a+'\n', strict=True)
            if len(seq) > CTX:
                raise ValueError('Context overflow: %r' % e)
        key = (q, tuple(normalize(a) for a in answers))
        if key in seen:
            raise ValueError('Duplicate: %r' % e)
        seen.add(key)
    train_q = {normalize(e['question']) for e in train}
    assert not train_q.intersection(normalize(e['question']) for e in test)
    rng = random.Random(seed)
    # Balanced control set: familiar, paraphrase, arithmetic, unknown, special letters.
    control = []
    for split in ['familiar', 'paraphrase']:
        pool = [e for e in test if e['category'] not in ('арифметика', 'неизвестное')]
        for e in rng.sample(pool, 40):
            z = dict(e, split=split)
            if split == 'familiar':
                index=int(e['fact_id'][3:])
                z['question'] = fs[index]['questions'][fs[index]['train_form']]
            control.append(z)
    for category, n in [('арифметика', 30), ('неизвестное', 15)]:
        control.extend(dict(e, split=category) for e in rng.sample([e for e in test if e['category']==category], n))
    for f in fs:
        if any(c in f['questions'][0] + f['answers'][0] for c in 'ёйъь') and f['category']!='арифметика':
            index=int(f['id'][3:])
            control.append(dict(fact_id=f['id'],category=f['category'],question=f['questions'][f['train_form']],answers=f['answers'],split='special_letters'))
            if sum(e['split']=='special_letters' for e in control)==15:
                break
    # Preserve insertion order and report distribution honestly.
    payloads = {'facts.jsonl':fs, 'train.jsonl':train, 'test.jsonl':test, 'control.jsonl':control}
    hashes = {}
    for filename, rows in payloads.items():
        path=destination/filename
        path.write_text(''.join(json.dumps(e,ensure_ascii=False)+'\n' for e in rows),encoding='utf-8')
        hashes[filename]=hashlib.sha256(path.read_bytes()).hexdigest()
    form_split={str(parity):dict(collections.Counter(str(f['train_form']) for f in fs if 'expression' in f and f['expression'][2]%2==parity)) for parity in [0,1]}
    manifest=dict(seed=seed, vocab_sha256=FINGERPRINT, facts=len(fs), train=len(train), test=len(test), control=len(control), categories=dict(collections.Counter(f['category'] for f in fs)), arithmetic_form_by_y_parity=form_split, sha256=hashes, license='MIT; original wording and programmatically checked arithmetic', caveat='1000+ total includes arithmetic; editorial entries are not independently source-audited')
    (destination/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(manifest,ensure_ascii=False,indent=2))


if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--out',type=Path,default=ROOT/'data')
    p.add_argument('--seed',type=int,default=42)
    args=p.parse_args()
    build(args.out,args.seed)
