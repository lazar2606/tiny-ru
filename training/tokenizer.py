"""Single vocabulary authority: UTF-8 during training, CP866 in DOS."""
import hashlib
import json
import unicodedata
from pathlib import Path

SPEC_PATH = Path(__file__).with_name('vocab.json')
SPEC = json.loads(SPEC_PATH.read_text(encoding='utf-8'))
CHARS = SPEC['characters']
VOCAB = len(CHARS) + 2
assert VOCAB == 97 and len(set(CHARS)) == len(CHARS)
TO_ID = {c: i + 2 for i, c in enumerate(CHARS)}
PAD, EOS, UNK = 0, 1, TO_ID[SPEC['unknown']]
FINGERPRINT = hashlib.sha256(SPEC_PATH.read_bytes()).hexdigest()
TRANSLATE = str.maketrans({'—': '-', '–': '-', '−': '-', '«': '"', '»': '"', '…': '...', '\u00a0': ' ', '\r': ''})


def normalize(text):
    return unicodedata.normalize('NFC', text).lower().translate(TRANSLATE)


def encode(text, strict=False):
    result = []
    for c in normalize(text):
        if c == '\n':
            result.append(EOS)
        elif c in TO_ID:
            result.append(TO_ID[c])
        elif strict:
            raise ValueError('Unsupported character: %r' % c)
        else:
            result.append(UNK)
    return result


def decode(ids):
    out = []
    for i in ids:
        if not 0 <= i < VOCAB:
            raise ValueError('Token out of range: %r' % i)
        if i:
            out.append('\n' if i == EOS else CHARS[i - 2])
    return ''.join(out)


def generate_header(path):
    cp_to_id = [UNK] * 256
    for c, i in TO_ID.items():
        cp_to_id[c.encode('cp866')[0]] = i
        cp_to_id[c.upper().encode('cp866')[0]] = i
    cp_to_id[10] = EOS
    cp_to_id[13] = EOS
    cp_to_id[255] = TO_ID[' ']  # CP866 NBSP, matching Python normalization.
    id_to_cp = [0, 10] + list(CHARS.encode('cp866'))
    text = '/* Generated by training/tokenizer.py; do not edit. */\n'
    text += '#define RU_VOCAB 97\n#define RU_UNK %d\n' % UNK
    text += '#define RU_VOCAB_SHA "%s"\n' % FINGERPRINT
    for name, values in [('ru_cp_to_id', cp_to_id), ('ru_id_to_cp', id_to_cp)]:
        text += 'static const unsigned char %s[%d] = {\n' % (name, len(values))
        text += ',\n'.join('  ' + ','.join(map(str, values[i:i+16])) for i in range(0, len(values), 16)) + '\n};\n'
    Path(path).write_text(text, encoding='ascii')


if __name__ == '__main__':
    generate_header(Path(__file__).resolve().parents[1] / 'dos' / 'VOCAB.H')
