"""Emit ASCII-only C source literals containing CP866 UI bytes."""
from pathlib import Path

STRINGS={
    'RU_TITLE':'Tiny-RU 2.1r3 - русская нейросеть для DOS.\n',
    'RU_WINDOWS_TITLE':'Tiny-RU 2.1r3 - русская нейросеть для Windows x64.\n',
    'RU_WINDOWS_READY':'Готово. Введите вопрос.\n',
    'RU_WINDOWS_MODEL_MISSING':'Не найден TINY.BIN. Положите его рядом с TINYWIN.EXE.',
    'RU_LOADING':'Загрузка TINY.BIN ...\n',
    'RU_READY':'Готово: слоёв %d, размерность %d, творчество %d.\n',
    'RU_TOPICS':'Спросите о России, природе, технике или простых числах.\n',
    'RU_QUIT':'Для выхода введите QUIT.\n',
    'RU_LONG':'Вопрос слишком длинный (не более %d символов).\n',
    'RU_BYE':'До свидания!\n',
    'RU_HELLO':'Привет! Я Тини, маленькая нейросеть.',
    'RU_ASK':'Спросите о странах, природе, технике или числах.',
    'RU_DEMO1':'как называется столица россии?',
    'RU_DEMO2':'кит является рыбой?',
    'RU_DEMO3':'сколько будет 7*8?',
    'RU_DEMO4':'как называется буква ъ?',
    'RU_DEMO5':'какая буква после е в русском алфавите?',
    'RU_DEMO6':'как тебя зовут?',
}


def generate():
    text='/* Generated by scripts/generate_strings.py; CP866. */\n'
    for name,value in STRINGS.items():
        literal=''.join('\\%03o'%b for b in value.encode('cp866'))
        text+='#define %s "%s"\n'%(name,literal)
    return text


if __name__=='__main__':
    (Path(__file__).resolve().parents[1]/'dos/RUSTR.H').write_text(generate(),encoding='ascii')
